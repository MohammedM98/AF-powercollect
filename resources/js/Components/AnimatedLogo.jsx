/**
 * The company's AF mark, drawn in when it appears: its outlines trace
 * themselves, the red dots pop in one after another and the metal finish
 * wipes across; then it floats, a shine passes over it now and then, and it
 * tilts toward the pointer. Shown finished at once to those who ask their
 * device for less motion.
 */
export default function AnimatedLogo({ className = '', label = 'شعار شركة أبو زايد' }) {
    const [stage, setStage] = useState('play');
    const svgRef = useRef(null);
    const wipeId = `af-wipe-${useId().replace(/[^\w-]/g, '')}`;

    useEffect(() => {
        if (window.matchMedia?.('(prefers-reduced-motion: reduce)').matches) {
            setStage('done');
            return undefined;
        }

        const timer = setTimeout(() => setStage('done'), 4500);
        return () => clearTimeout(timer);
    }, []);

    function tilt(event) {
        if (stage !== 'done') {
            return;
        }

        const box = event.currentTarget.getBoundingClientRect();
        const x = (event.clientX - box.left) / box.width - 0.5;
        const y = (event.clientY - box.top) / box.height - 0.5;
        svgRef.current.style.transform = `rotateY(${x * 14}deg) rotateX(${-y * 12}deg)`;
    }

    return (
        <div
            className={`af-logo ${stage} ${className}`}
            role="img"
            aria-label={label}
            onPointerMove={tilt}
            onPointerLeave={() => (svgRef.current.style.transform = '')}
        >
            <svg ref={svgRef} viewBox="0 0 782 455" aria-hidden="true">
                <defs>
                    <clipPath id={wipeId}>
                        <rect className="wipe" x="-20" y="-30" width="822" height="515" />
                    </clipPath>
                </defs>
                <g className="tint">
                    <path className="tint-af" d={SHAPES.af} />
                    <path className="tint-silver" d={SHAPES.swoosh} />
                    <path className="tint-red" d={SHAPES.red} />
                </g>
                <image href={IMAGE} width="782" height="455" clipPath={`url(#${wipeId})`} />
                <g className="lines">
                    <path className="st st-af" pathLength="1" d={SHAPES.af} />
                    <path className="st st-sw" pathLength="1" d={SHAPES.swoosh} />
                    <path className="st st-red" pathLength="1" d={SHAPES.red} />
                    {HOLES.map((d) => (
                        <path key={d} className="st st-hole" pathLength="1" d={d} />
                    ))}
                </g>
                <g className="dots">
                    {DOTS.map(([cx, cy, r], index) => (
                        <circle key={index} className="dot" style={{ '--i': index }} cx={cx} cy={cy} r={r} />
                    ))}
                </g>
            </svg>
            <div className="shine" style={{ WebkitMaskImage: `url(${IMAGE})`, maskImage: `url(${IMAGE})` }} aria-hidden="true" />
        </div>
    );
}
